import crypto from "node:crypto"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import vm from "node:vm"

const COMMIT = "a3b47b37cba97dd637de517aab52c45ec0f83456"
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const vendorDir = path.join(root, "vendor/tweakcn")
const sourcePath = path.join(vendorDir, "theme-presets.ts")
const licensePath = path.join(vendorDir, "LICENSE")
const pinsPath = path.join(vendorDir, "pins.json")
const outTs = path.join(root, "src/lib/theme-catalog.generated.ts")
const outJs = path.join(root, "public/theme-init.js")
const outLicense = path.join(root, "public/licenses/APACHE-2.0.txt")

function sha256(file) {
  return crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex")
}

function verifyPins() {
  const pins = JSON.parse(fs.readFileSync(pinsPath, "utf8"))
  if (pins.commit !== COMMIT) {
    throw new Error(`pins commit ${pins.commit} 与脚本固定版本不一致`)
  }
  for (const [name, hash] of Object.entries(pins.files)) {
    const actual = sha256(path.join(vendorDir, name))
    if (actual !== hash) {
      throw new Error(`${name} 的 SHA-256 与 pins.json 不一致`)
    }
  }
}

function stringsOnly(record) {
  const result = {}
  for (const [key, value] of Object.entries(record ?? {})) {
    if (typeof value === "string" && value.trim()) result[key] = value.trim()
  }
  return result
}

function loadPresets() {
  const text = fs.readFileSync(sourcePath, "utf8")
  const marker = text.indexOf("= {")
  const end = text.lastIndexOf("}")
  if (marker < 0 || end < marker) throw new Error("未找到 defaultPresets")
  const record = vm.runInNewContext(`(${text.slice(marker + 2, end + 1)})`, Object.create(null), {
    timeout: 1000,
  })
  if (!record || typeof record !== "object") throw new Error("主题对象无法解析")
  const presets = []
  const seen = new Set()
  for (const [id, value] of Object.entries(record)) {
    if (!value?.styles?.light || !value?.styles?.dark) throw new Error(`主题 ${id} 缺少 light/dark`)
    if (seen.has(id)) throw new Error(`主题 ID 重复：${id}`)
    seen.add(id)
    presets.push({
      id,
      label: typeof value.label === "string" ? value.label : id,
      source: "TWEAKCN",
      sourceCommit: COMMIT,
      styles: { light: stringsOnly(value.styles.light), dark: stringsOnly(value.styles.dark) },
    })
  }
  if (!seen.has("modern-minimal")) throw new Error("缺少默认主题 modern-minimal")
  presets.sort((a, b) => a.label.localeCompare(b.label, "en") || a.id.localeCompare(b.id))
  const preferred = presets.findIndex((item) => item.id === "modern-minimal")
  if (preferred > 0) {
    const [item] = presets.splice(preferred, 1)
    presets.unshift(item)
  }
  return presets
}

function renderTs(presets) {
  return `// Generated by scripts/sync-tweakcn-themes.mjs. Do not edit.
// Source: https://github.com/jnsahaj/tweakcn @ ${COMMIT} (Apache-2.0)
import type { ThemePreset } from "./theme-types.ts"

export const tweakcnCommit = ${JSON.stringify(COMMIT)}
export const themePresets: ThemePreset[] = ${JSON.stringify(presets)}
`
}

function renderInit(presets) {
  return `/* Generated from tweakcn ${COMMIT}. Apache-2.0. */
(function () {
  var STORAGE_KEY = "repository-sync.theme";
  var DEFAULT_ID = "modern-minimal";
  var presets = ${JSON.stringify(presets)};
  function find(id) {
    for (var i = 0; i < presets.length; i += 1) if (presets[i].id === id) return presets[i];
    return null;
  }
  try {
    var raw = null;
    try { raw = localStorage.getItem(STORAGE_KEY); } catch (e) { raw = null; }
    var parsed = raw ? JSON.parse(raw) : null;
    var id = parsed && parsed.version === 1 && find(parsed.themeId) ? parsed.themeId : DEFAULT_ID;
    var mode = parsed && (parsed.mode === "light" || parsed.mode === "dark" || parsed.mode === "system") ? parsed.mode : "system";
    var dark = false;
    try { dark = window.matchMedia("(prefers-color-scheme: dark)").matches; } catch (e) { dark = false; }
    var resolved = mode === "system" ? (dark ? "dark" : "light") : mode;
    var preset = find(id) || find(DEFAULT_ID);
    if (!preset) return;
    var styles = preset.styles[resolved] || {};
    var root = document.documentElement;
    root.dataset.theme = preset.id;
    root.dataset.mode = mode;
    root.dataset.resolvedMode = resolved;
    root.style.colorScheme = resolved;
    if (resolved === "dark") root.classList.add("dark");
    else root.classList.remove("dark");
    Object.keys(styles).forEach(function (key) {
      var value = styles[key];
      if (typeof value !== "string" || !value || /[;{}]|url\\s*\\(/i.test(value)) return;
      if (!/^[a-z0-9-]+$/i.test(key)) return;
      root.style.setProperty("--" + key, value);
    });
  } catch (e) {}
})();
`
}

verifyPins()
const presets = loadPresets()
const tsText = renderTs(presets)
const jsText = renderInit(presets)
const licenseText = fs.readFileSync(licensePath)
const check = process.argv.includes("--check")
if (check) {
  const same =
    fs.existsSync(outTs) &&
    fs.readFileSync(outTs, "utf8") === tsText &&
    fs.existsSync(outJs) &&
    fs.readFileSync(outJs, "utf8") === jsText &&
    fs.existsSync(outLicense) &&
    fs.readFileSync(outLicense).equals(licenseText)
  if (!same) {
    console.error("主题产物与锁定的上游不一致，请运行 node scripts/sync-tweakcn-themes.mjs")
    process.exit(1)
  }
  console.log(`ok ${presets.length} themes`)
} else {
  fs.mkdirSync(path.dirname(outTs), { recursive: true })
  fs.mkdirSync(path.dirname(outJs), { recursive: true })
  fs.mkdirSync(path.dirname(outLicense), { recursive: true })
  fs.writeFileSync(outTs, tsText)
  fs.writeFileSync(outJs, jsText)
  fs.writeFileSync(outLicense, licenseText)
  console.log(`wrote ${presets.length} themes`)
}
